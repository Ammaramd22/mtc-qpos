-- QPOS POS Exchange / Trade-In table (cPanel phpMyAdmin)
-- Safe to run multiple times.

CREATE TABLE IF NOT EXISTS `pos_trade_ins` (
  `id` int(10) unsigned NOT NULL AUTO_INCREMENT,
  `business_id` int(10) unsigned NOT NULL,
  `transaction_id` int(10) unsigned NOT NULL,
  `sell_line_id` int(10) unsigned DEFAULT NULL,
  `location_id` int(10) unsigned NOT NULL,
  `contact_id` int(10) unsigned DEFAULT NULL,
  `created_by` int(10) unsigned DEFAULT NULL,
  `new_product_id` int(10) unsigned DEFAULT NULL,
  `new_variation_id` int(10) unsigned DEFAULT NULL,
  `new_product_name` varchar(255) DEFAULT NULL,
  `new_unit_price` decimal(22,4) NOT NULL DEFAULT 0.0000,
  `new_quantity` decimal(22,4) NOT NULL DEFAULT 1.0000,
  `old_product_id` int(10) unsigned DEFAULT NULL,
  `old_variation_id` int(10) unsigned DEFAULT NULL,
  `opening_stock_transaction_id` int(10) unsigned DEFAULT NULL,
  `old_product_name` varchar(255) DEFAULT NULL,
  `brand_name` varchar(191) DEFAULT NULL,
  `brand_id` int(10) unsigned DEFAULT NULL,
  `tyre_size` varchar(100) DEFAULT NULL,
  `category_id` int(10) unsigned DEFAULT NULL,
  `sub_category_id` int(10) unsigned DEFAULT NULL,
  `condition` varchar(100) DEFAULT NULL,
  `usage_percent` decimal(8,2) DEFAULT NULL,
  `barcode` varchar(191) DEFAULT NULL,
  `quantity` decimal(22,4) NOT NULL DEFAULT 1.0000,
  `exchange_value` decimal(22,4) NOT NULL DEFAULT 0.0000,
  `notes` text DEFAULT NULL,
  `reason` varchar(255) DEFAULT NULL,
  `status` varchar(50) NOT NULL DEFAULT 'completed',
  `created_at` timestamp NULL DEFAULT NULL,
  `updated_at` timestamp NULL DEFAULT NULL,
  PRIMARY KEY (`id`),
  KEY `pos_trade_ins_business_transaction` (`business_id`,`transaction_id`),
  KEY `pos_trade_ins_sell_line_id` (`sell_line_id`),
  KEY `pos_trade_ins_old_product_id` (`old_product_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
